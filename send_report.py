def get_alert_summary():
    """Get top alert anomalies from dbt model"""
    conn = snowflake.connector.connect(**SNOWFLAKE_CONFIG)
    cursor = conn.cursor()
    
    cursor.execute("""
        SELECT machine_id, metric_name, alert_count, last_alert
        FROM alert_frequency
        ORDER BY alert_count DESC
        LIMIT 10
    """)
    
    rows = cursor.fetchall()
    conn.close()
    return rows

def get_uptime_summary():
    """Get machine uptime percentages from dbt model"""
    conn = snowflake.connector.connect(**SNOWFLAKE_CONFIG)
    cursor = conn.cursor()
    
    cursor.execute("""
        SELECT machine_id, uptime_pct, anomaly_readings, total_readings
        FROM machine_uptime_pct
        ORDER BY uptime_pct ASC
        LIMIT 10
    """)
    
    rows = cursor.fetchall()
    conn.close()
    return rows

def format_report(alerts, uptime):
    """Format HTML email report"""
    alert_rows = ''.join([
        f"<tr><td>{row[0]}</td><td>{row[1]}</td><td>{row[2]}</td><td>{row[3]}</td></tr>"
        for row in alerts
    ])
    
    uptime_rows = ''.join([
        f"<tr><td>{row[0]}</td><td>{row[1]}%</td><td>{row[2]}</td><td>{row[3]}</td></tr>"
        for row in uptime
    ])
    
    html = f"""
    <html>
        <body style="font-family: Arial, sans-serif;">
            <h2>Factory Maintenance Report - EOD</h2>
            
            <h3>Top Alert Anomalies</h3>
            <table border="1" cellpadding="5">
                <tr>
                    <th>Machine</th>
                    <th>Metric</th>
                    <th>Alert Count</th>
                    <th>Last Alert</th>
                </tr>
                {alert_rows}
            </table>
            
            <h3>Machine Uptime (Lowest First)</h3>
            <table border="1" cellpadding="5">
                <tr>
                    <th>Machine</th>
                    <th>Uptime %</th>
                    <th>Anomalies</th>
                    <th>Total Readings</th>
                </tr>
                {uptime_rows}
            </table>
            
            <p><small>Generated by Airflow EOD Pipeline</small></p>
        </body>
    </html>
    """
    return html

def send_email(html_content):
    """Send HTML email report"""
    msg = MIMEMultipart('alternative')
    msg['Subject'] = 'Factory Maintenance Report - EOD'
    msg['From'] = EMAIL_SENDER
    msg['To'] = EMAIL_RECIPIENT
    
    part = MIMEText(html_content, 'html')
    msg.attach(part)
    
    try:
        server = smtplib.SMTP('smtp.gmail.com', 587)
        server.starttls()
        server.login(EMAIL_SENDER, EMAIL_PASSWORD)
        server.sendmail(EMAIL_SENDER, EMAIL_RECIPIENT, msg.as_string())
        server.quit()
        print("✓ Email sent successfully")
        return True
    except Exception as e:
        print(f"✗ Email send failed: {e}")
        return False

def main():
    """Query dbt models and send report"""
    try:
        print("Querying alert summary...")
        alerts = get_alert_summary()
        
        print("Querying uptime summary...")
        uptime = get_uptime_summary()
        
        print("Formatting report...")
        html = format_report(alerts, uptime)
        
        print("Sending email...")
        send_email(html)
        
        print("✓ Report complete")
    except Exception as e:
        print(f"✗ Report failed: {e}")
        raise

if __name__ == '__main__':
    main()
